#!/usr/bin/env python3
"""Render the stack-specific sections of the slot skills from stack/profile.env.

  python3 scripts/core/apply_stack.py            # render
  python3 scripts/core/apply_stack.py --check    # exit 1 if rendered files are stale
  python3 scripts/core/apply_stack.py --profile stack/presets/NAME.env   # render from a preset (copies it to stack/profile.env)

Replaces text between `<!-- stack:begin -->` and `<!-- stack:end -->` in
.claude/skills/{backend,frontend,database,testing}/SKILL.md and AGENTS.md, and writes docs/stack-versions.md.
Everything outside the markers is left alone, so the render is idempotent.
"""
import re, sys, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROFILE = ROOT / "stack" / "profile.env"
KINDS = {  # skill -> (profile key, command prefixes shown)
    "backend": ("BACKEND", ["BACKEND_BUILD_CMD", "BACKEND_LINT_CMD", "BACKEND_TEST_CMD", "BACKEND_RUN_CMD"]),
    "frontend": ("FRONTEND", ["FRONTEND_BUILD_CMD", "FRONTEND_LINT_CMD", "FRONTEND_TEST_CMD", "FRONTEND_RUN_CMD"]),
    "database": ("DATABASE", ["DB_STATUS_CMD", "DB_MIGRATE_CMD", "DB_SEED_CMD", "DB_RESET_CMD", "DB_SNAPSHOT_CMD", "DB_RESTORE_CMD", "DB_READONLY_CMD"]),
    "testing": ("TESTING", ["TEST_FOCUSED_CMD", "TEST_CHANGED_CMD", "TEST_ALL_CMD"]),
}
BEGIN, END = "<!-- stack:begin -->", "<!-- stack:end -->"
BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)


def parse(path: Path) -> dict:
    env = {}
    for n, line in enumerate(path.read_text().splitlines(), 1):
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        if "=" not in s:
            sys.exit(f"{path}:{n}: expected KEY=value")
        k, v = s.split("=", 1)
        v = v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
            v = v[1:-1]
        env[k.strip()] = v
    return env


def used(v: str) -> bool:
    return v not in ("", "none")


def table(env: dict, keys: list) -> str:
    rows = [(k, env[k]) for k in keys if used(env.get(k, ""))]
    if not rows:
        return "_No commands defined in the profile._\n"
    out = "| Task | Command |\n|---|---|\n"
    for k, v in rows:
        out += f"| `{k}` | `{v}` |\n"
    return out


def skill_block(kind: str, env: dict) -> str:
    key, cmds = KINDS[kind]
    val = env.get(key, "none")
    if not used(val):
        return (f"{BEGIN}\n## Stack\n\nNot defined for {kind} in `stack/profile.env` (`{key}=none`). "
                f"Pick a fragment from `stack/fragments/{kind}/`, set `{key}=<name>`, then run `python3 scripts/core/apply_stack.py`.\n\n"
                f"### Commands\n\n{table(env, cmds)}{END}")
    frag = ROOT / "stack" / "fragments" / kind / f"{val}.md"
    if not frag.exists():
        sys.exit(f"profile says {key}={val} but {frag.relative_to(ROOT)} does not exist (copy _template.md)")
    body = frag.read_text().strip()
    return (f"{BEGIN}\n## Stack: {val}\n\n_Rendered from `stack/fragments/{kind}/{val}.md` and `stack/profile.env`. "
            f"Do not edit between the markers; edit the fragment or profile and re-run `scripts/core/apply_stack.py`._\n\n"
            f"{body}\n\n### Commands\n\n{table(env, cmds)}{END}")


def agents_block(env: dict) -> str:
    name = env.get("STACK_NAME", "unnamed")
    parts = [f"{BEGIN}\n## Stack\n\n**{name}**. Conventions and commands come from `stack/profile.env` and the rendered skills "
             f"(`backend`, `frontend`, `database`, `testing`). Re-render with `python3 scripts/core/apply_stack.py` after changing the profile; "
             f"`scripts/core/doctor.sh` fails if they are stale.\n"]
    sel = [f"{k.title()}: {env.get(v[0], 'none')}" for k, v in KINDS.items()]
    parts.append("\n" + " · ".join(sel) + "\n")
    allcmds = [c for _, (_, cs) in KINDS.items() for c in cs]
    gate = [k for k in ("TEST_FOCUSED_CMD", "TEST_CHANGED_CMD", "TEST_ALL_CMD") if used(env.get(k, ""))]
    if gate:
        parts.append("\n" + table(env, gate))
    parts.append(f"\nGates: `sh scripts/core/gate.sh focused|changed|all`. Database: `sh scripts/core/db.sh status|migrate|seed|reset|snapshot|restore|psql`.\n{END}")
    return "".join(parts)


def versions_doc(env: dict) -> str:
    v = {k[8:]: val for k, val in env.items() if k.startswith("VERSION_") and used(val)}
    out = "# Stack versions\n\n_Generated by `scripts/core/apply_stack.py` from `stack/profile.env`. Edit the profile, not this file._\n\n"
    if not v:
        return out + "No versions pinned.\n"
    out += "| Tool | Version |\n|---|---|\n" + "".join(f"| {k.lower()} | {val} |\n" for k, val in sorted(v.items()))
    return out + "\nA dependency outside this baseline needs an ADR.\n"


def main() -> int:
    args = sys.argv[1:]
    check = "--check" in args
    if "--profile" in args:
        src = ROOT / args[args.index("--profile") + 1]
        if not src.exists():
            sys.exit(f"no such preset: {src}")
        if not check:
            shutil.copyfile(src, PROFILE)
    if not PROFILE.exists():
        print("no stack/profile.env: generic mode (copy stack/profile.example.env or a preset)")
        return 0
    env = parse(PROFILE)
    targets = {ROOT / ".claude" / "skills" / k / "SKILL.md": skill_block(k, env) for k in KINDS}
    targets[ROOT / "AGENTS.md"] = agents_block(env)
    stale = []
    for path, block in targets.items():
        text = path.read_text()
        if not BLOCK.search(text):
            sys.exit(f"{path.relative_to(ROOT)}: stack markers missing")
        new = BLOCK.sub(lambda _m: block, text, count=1)
        if new != text:
            stale.append(path)
            if not check:
                path.write_text(new)
    vdoc = ROOT / "docs" / "stack-versions.md"
    vnew = versions_doc(env)
    if not vdoc.exists() or vdoc.read_text() != vnew:
        stale.append(vdoc)
        if not check:
            vdoc.write_text(vnew)
    for p in stale:
        print(("STALE " if check else "wrote ") + str(p.relative_to(ROOT)))
    if not stale:
        print("up to date")
    return 1 if (check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
